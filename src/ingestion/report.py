"""Build evidence/AC01/<run>/ingestion_report.md from that run's manifests and Spark profiles.

Every number in the report is copied from manifest_<source>.json / profile_<source>.json of the
same run; nothing is typed in by hand (CLAUDE.md integrity rule).
Run: python -m src.ingestion.report evidence/AC01/m1_<timestamp>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

SOURCES = ["uci_metro", "open_meteo", "nyc_tlc", "kitti"]


def load(path: Path) -> dict[str, Any] | None:
    if not path.exists() or path.stat().st_size == 0:
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def fmt(v: Any) -> str:
    if isinstance(v, bool):
        return "yes" if v else "**NO**"
    if isinstance(v, int):
        return f"{v:,}"
    return "" if v is None else str(v)


def file_table(man: dict[str, Any]) -> list[str]:
    out = ["| File | Status | Bytes | SHA-256 (first 16) | Source version |", "|---|---|---:|---|---|"]
    files = man["files"]
    shown = files if len(files) <= 12 else files[:5]
    for f in shown:
        out.append(f"| `{f['name']}` | {f['status']} | {fmt(f.get('bytes'))} | "
                   f"`{(f.get('sha256') or '')[:16]}` | {fmt(f.get('source_version'))} |")
    if len(files) > len(shown):
        out.append(f"| … {len(files) - len(shown)} more files (see manifest) | | | | |")
    return out


def section(source: str, man: dict[str, Any] | None, prof: dict[str, Any] | None) -> list[str]:
    out = [f"## {source}", ""]
    if man is None:
        return out + ["Not run in this run (no manifest).", ""]
    status = {s: sum(1 for f in man["files"] if f["status"] == s) for s in {f["status"] for f in man["files"]}}
    out += [f"- Manifest: {len(man['files'])} files, status counts {status}",
            f"- Fetch started {man['started_at']}, finished {man.get('finished_at')}"]
    out += [""] + file_table(man) + [""]
    if prof is None:
        return out + ["**No Spark profile** — the Bronze job failed or did not run; see bronze log.", ""]
    integ = prof["integrity"]
    out += ["**Integrity (SHA-256 recomputed by Spark on the HDFS copy):** "
            f"{integ['sha256_match']}/{integ['files_in_manifest']} match; "
            f"mismatch {integ['sha256_mismatch'] or 'none'}; missing in HDFS {integ['missing_in_hdfs'] or 'none'}; "
            f"bytes in HDFS {fmt(integ['bytes_in_hdfs'])}.", ""]
    skip = {"source", "ingest_date", "integrity", "manifest_status_counts", "manifest_failures",
            "schema", "months", "rows_per_file", "grid_points", "object_type_counts", "zone_lookup"}
    out += ["| Metric | Value |", "|---|---|"]
    for k, v in prof.items():
        if k not in skip:
            out.append(f"| {k} | {fmt(v) if not isinstance(v, (dict, list)) else '`' + json.dumps(v, default=str) + '`'} |")
    out.append("")
    if "months" in prof:
        out += ["| Month | Rows | Pickup outside file month | Null passenger_count | Pickup min | Pickup max |",
                "|---|---:|---:|---:|---|---|"]
        for m, v in prof["months"].items():
            out.append(f"| {m} | {fmt(v['rows'])} | {fmt(v['pickup_outside_file_month'])} | "
                       f"{fmt(v['null_passenger_count'])} | {v['pickup_min']} | {v['pickup_max']} |")
        out += ["", f"Zone lookup: {fmt(prof['zone_lookup']['rows'])} rows.", ""]
    for key in ("rows_per_file", "grid_points", "object_type_counts"):
        if key in prof:
            out += [f"`{key}`: `{json.dumps(prof[key], default=str)}`", ""]
    if "schema" in prof:
        out += [f"Schema: `{prof['schema']}`", ""]
    elif "months" in prof:
        first = next(iter(prof["months"].values()))
        out += [f"Schema ({first['file']}): `{first['schema']}`", ""]
    if prof.get("manifest_failures"):
        out += ["**Failures:**", *[f"- `{f['name']}`: {f['error']}" for f in prof["manifest_failures"]], ""]
    return out


def main() -> int:
    run = Path(sys.argv[1])
    lines = [f"# Ingestion report — {run.name}", "",
             "Generated by `src/ingestion/report.py` from this run's manifests and Spark profiles.", ""]
    summary = ["| Source | Files | Failed | Integrity OK | Profile OK |", "|---|---:|---:|---|---|"]
    body: list[str] = []
    for s in SOURCES:
        man, prof = load(run / f"manifest_{s}.json"), load(run / f"profile_{s}.json")
        if man:
            failed = sum(1 for f in man["files"] if f["status"] == "failed")
            integ_ok = prof is not None and not prof["integrity"]["sha256_mismatch"] and not prof["integrity"]["missing_in_hdfs"]
            summary.append(f"| {s} | {len(man['files'])} | {failed} | {fmt(integ_ok)} | {fmt(bool(prof and prof.get('ok')))} |")
        body += section(s, man, prof)
    (run / "ingestion_report.md").write_text("\n".join(lines + summary + [""] + body) + "\n", encoding="utf-8")
    print(run / "ingestion_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
